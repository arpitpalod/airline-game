declare v_id uuid;
begin
  if exists (select 1 from public.worlds where name = 'Test World' and status <> 'setup') then
    delete from public.worlds where name = 'Test World';
    insert into public.worlds (name, speed, demand_scale, max_airlines, pilots)
    values ('Test World', 168, 0.5, 25, true) returning id into v_id;
    insert into public.world_secrets (world_id, invite_code)
    values (v_id, substr(md5(random()::text || clock_timestamp()::text), 1, 8));
  end if;
end $$;
