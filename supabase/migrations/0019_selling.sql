-- Migration 0019: selling 26 weeks ahead (spec section 19, step 2). Every flight goes on sale 26 weeks before it flies.
-- Each route is sold by one of four strategies (fill, balanced, top, follow); the engine prices every flight week from
-- the strategy, how it is selling against its target curve, weeks to departure and, for "follow", rivals' fares. There
-- are no fare levels and players no longer set fares. Travellers of each type book on their own curve. Cash comes in when
-- a ticket is sold; revenue counts when the flight flies. Overbooking is automatic; no-shows follow hidden patterns by
-- market. Selling runs once a week, at the start of the week, before the week's flights. Worlds with selling = false
-- keep the daily demand of section 4 (the checks written before this migration run in such worlds).

