-- How each strategy prices (G). Economy fares are multiples of the market's reference fare, business fares of the
-- business reference (reference x biz_fare_mult). A flight week's fare starts at early_mult 26 weeks out and rises to
-- late_mult in the week it flies. Each week the engine compares seats sold with the target curve (target_lf x the share
-- of travellers who would have booked by then) and moves that week's fares by step when it is more than band ahead of or
-- behind it, within min_mult and max_mult. "follow" prices at the rivals' average for the same week x (1 + follow_gap),
-- and runs as balanced where it has no rival. Overbooking: seats sold beyond the cabin, as a share of expected no-shows.
create table public.rm_strategies (
  key            text primary key check (key in ('fill', 'balanced', 'top', 'follow')),
  name           text not null,
  blurb          text not null,
  sort           int not null,
  target_lf      numeric not null check (target_lf > 0 and target_lf <= 1),
  early_mult     numeric not null check (early_mult > 0),
  late_mult      numeric not null check (late_mult > 0),
  biz_early_mult numeric not null check (biz_early_mult > 0),
  biz_late_mult  numeric not null check (biz_late_mult > 0),
  min_mult       numeric not null check (min_mult > 0),
  max_mult       numeric not null,
  step           numeric not null check (step >= 0 and step < 0.5),
  band           numeric not null check (band >= 0 and band < 1),
  follow_gap     numeric not null default 0 check (follow_gap between -0.5 and 0.5),
  overbook       numeric not null check (overbook between 0 and 3),
  check (max_mult > min_mult)
);
